/**
 * The admin's and the portal's Content-Security-Policy and companion headers (SPEC §11;
 * G-24, ADR-0021), in one place for both servers that send them:
 *
 * - production: the frontend image's nginx, from templates this module renders at build
 *   time (`renderNginx`); the nonce is nginx's per-request `$request_id`, put into
 *   index.html by `sub_filter`, and the media origins come from Django at container start;
 * - development: the Vite dev servers, through `cspPlugin`, with a fresh nonce per page
 *   and the HMR websocket allowed.
 *
 * No inline script is allowed anywhere. Styles the libraries add at run time (sonner,
 * Radix's scroll lock and select) carry the nonce from `<meta property="csp-nonce">`.
 *
 * Plain JavaScript (with types in policy.d.ts), so Node runs it without a build step.
 */

/** In index.html until the server replaces it: letters and digits only (a valid nonce). */
export const NONCE_PLACEHOLDER = "CSPNONCE7f3a9c0b";
export const REPORT_PATH = "/api/v1/csp-report";

const YOUTUBE = "https://www.youtube-nocookie.com";
const TMDB_IMAGES = "https://image.tmdb.org";
/** TheTVDB candidates' artwork in the admin's review queue (ADR-0023). */
const TVDB_IMAGES = "https://artworks.thetvdb.com";

/**
 * @param {"admin" | "portal"} app
 * @param {{ mediaOrigins: readonly string[], nonce: string, connectExtra?: readonly string[], upgrade?: boolean }} options
 */
export function buildCsp(app, options) {
  const media = [...options.mediaOrigins];
  const nonce = `'nonce-${options.nonce}'`;
  const directives = [
    ["default-src", ["'none'"]],
    ["script-src", ["'self'", nonce]],
    ["style-src", ["'self'", nonce]],
    [
      "img-src",
      [
        "'self'",
        "data:",
        "blob:",
        ...media,
        ...(app === "admin" ? [TMDB_IMAGES, TVDB_IMAGES] : []),
      ],
    ],
    ["font-src", ["'self'", "data:"]],
    ["connect-src", ["'self'", ...media, ...(options.connectExtra ?? [])]],
    ["media-src", ["'self'", "blob:", ...media]],
    ["frame-src", ["'self'", ...(app === "portal" ? [YOUTUBE] : [])]],
    ["worker-src", ["'self'", "blob:"]],
    ["manifest-src", ["'self'"]],
    ["form-action", ["'self'"]],
    ["frame-ancestors", ["'none'"]],
    ["base-uri", ["'none'"]],
    ["object-src", ["'none'"]],
    ["report-uri", [REPORT_PATH]],
    ["report-to", ["csp"]],
  ];
  const parts = directives.map(([name, values]) => `${name} ${values.join(" ")}`);
  if (options.upgrade) parts.push("upgrade-insecure-requests");
  return parts.join("; ");
}

/** Browser features each app may use; everything else is off. */
export const PERMISSIONS_POLICY = {
  admin:
    "camera=(), microphone=(), geolocation=(), payment=(), usb=(), " +
    "publickey-credentials-get=(self), publickey-credentials-create=(self), " +
    "fullscreen=(self), picture-in-picture=(self)",
  portal:
    "camera=(), microphone=(), geolocation=(), payment=(), usb=(), " +
    `fullscreen=(self "${YOUTUBE}"), picture-in-picture=(self "${YOUTUBE}"), ` +
    `autoplay=(self "${YOUTUBE}"), encrypted-media=(self "${YOUTUBE}")`,
};

/** The trailer frame sets its own referrer policy (YouTube needs one). */
export const REFERRER_POLICY = {
  admin: "same-origin",
  portal: "strict-origin-when-cross-origin",
};

/**
 * The headers of an HTML page.
 * @param {"admin" | "portal"} app
 * @param {{ mediaOrigins: readonly string[], nonce: string, connectExtra?: readonly string[], upgrade?: boolean }} options
 * @returns {Record<string, string>}
 */
export function pageHeaders(app, options) {
  return {
    "Content-Security-Policy": buildCsp(app, options),
    "Permissions-Policy": PERMISSIONS_POLICY[app],
    "Referrer-Policy": REFERRER_POLICY[app],
    "Cross-Origin-Opener-Policy": "same-origin",
    "Reporting-Endpoints": `csp="${REPORT_PATH}"`,
  };
}

/** Media origins may only look like origins: they end up inside a header. */
const ORIGIN = /^https?:\/\/(\*\.)?[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?(:[0-9]{1,5})?$/;

/** @param {string} raw @returns {string[]} */
export function parseOrigins(raw) {
  return raw
    .split(/[\s,]+/)
    .map((item) => item.trim())
    .filter((item) => ORIGIN.test(item));
}

/**
 * The nginx include of one app: the headers, with `$request_id` as the nonce and
 * `__MEDIA_ORIGINS__` for the container to fill in at start (docker/nginx/30-csp.sh).
 * @param {"admin" | "portal"} app
 */
export function renderNginx(app) {
  const headers = pageHeaders(app, {
    mediaOrigins: ["__MEDIA_ORIGINS__"],
    nonce: "$request_id",
    upgrade: true,
  });
  const lines = [
    `# Generated by @smart-iptv/ui/csp at image build (ADR-0021); edit policy.js instead.`,
    ...Object.entries(headers).map(
      ([name, value]) => `add_header ${name} "${value.replaceAll('"', '\\"')}" always;`,
    ),
    "sub_filter_types text/html;",
    "sub_filter_once off;",
    `sub_filter '${NONCE_PLACEHOLDER}' '$request_id';`,
  ];
  return `${lines.join("\n")}\n`;
}

/** A page (index.html, or an app route the dev server answers with it), not a module. */
function isPage(/** @type {{ url?: string, headers: Record<string, unknown> }} */ req) {
  if (String(req.headers.accept ?? "").includes("text/html")) return true;
  const path = String(req.url ?? "/").split("?")[0] ?? "/";
  return !path.startsWith("/@") && !/\.[A-Za-z0-9]+$/.test(path.replace(/\.html$/, ""));
}

function randomNonce() {
  const bytes = new Uint8Array(16);
  globalThis.crypto.getRandomValues(bytes);
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
}

/**
 * Vite (development): the same policy on every HTML page, a fresh nonce in it and in the
 * page, and the HMR websocket in connect-src.
 * @param {"admin" | "portal"} app
 * @param {{ mediaOrigins: readonly string[], hmr: readonly string[] }} options
 */
export function cspPlugin(app, options) {
  return {
    name: "smart-iptv-csp",
    config() {
      return { html: { cspNonce: NONCE_PLACEHOLDER } };
    },
    /** @param {{ middlewares: { use: (fn: (req: any, res: any, next: () => void) => void) => void } }} server */
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const nonce = randomNonce();
        const headers = pageHeaders(app, {
          mediaOrigins: options.mediaOrigins,
          nonce,
          connectExtra: options.hmr,
        });
        // Every response carries the headers, as nginx sends them in production.
        for (const [name, value] of Object.entries(headers)) res.setHeader(name, value);
        if (!isPage(req)) {
          next();
          return;
        }
        // A fresh page every time: a 304 would keep the cached page's old nonce.
        delete req.headers["if-none-match"];
        delete req.headers["if-modified-since"];
        res.setHeader("Cache-Control", "no-store");
        /** @type {Uint8Array[]} */
        const chunks = [];
        const end = res.end.bind(res);
        res.write = (/** @type {any} */ chunk) => {
          if (chunk)
            chunks.push(typeof chunk === "string" ? new TextEncoder().encode(chunk) : chunk);
          return true;
        };
        res.end = (/** @type {any} */ chunk, /** @type {any[]} */ ...rest) => {
          if (chunk && typeof chunk !== "function") {
            chunks.push(typeof chunk === "string" ? new TextEncoder().encode(chunk) : chunk);
          }
          const body = Buffer.concat(chunks).toString("utf8").replaceAll(NONCE_PLACEHOLDER, nonce);
          if (!res.headersSent) res.setHeader("Content-Length", Buffer.byteLength(body));
          return end(body, ...rest.filter((item) => typeof item === "function"));
        };
        next();
      });
    },
  };
}
