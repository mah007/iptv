"""Only our edge and the live relay may call the internal stream-auth (G-16; ADR-0021).

They send the shared secret `edge_auth_token` (a Docker secret generated by
`scripts/secrets.sh`) as `X-Edge-Auth`; Django compares it in constant time. A container
that merely shares a Docker network with web (Traefik, the frontend, an exporter) can no
longer forge heartbeats or client addresses. Standalone edges (M15, ADR-0022) present
the same secret or their own credentials on the edges host.

The secret is read once per process: `EDGE_AUTH_TOKEN` (tests, development), else the
file in `EDGE_AUTH_TOKEN_FILE` (default `/run/secrets/edge_auth_token`). Without one,
every call is refused: the endpoint fails closed.
"""

import hmac
import os
from functools import cache
from pathlib import Path
from typing import Final

from django.conf import settings
from django.http import HttpRequest

HEADER: Final = "X-Edge-Auth"
DEFAULT_FILE: Final = "/run/secrets/edge_auth_token"


@cache
def expected() -> str:
    value = str(getattr(settings, "EDGE_AUTH_TOKEN", "") or os.environ.get("EDGE_AUTH_TOKEN", ""))
    if value:
        return value.strip()
    path = Path(os.environ.get("EDGE_AUTH_TOKEN_FILE", DEFAULT_FILE))
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError:
        return ""


def authenticated(request: HttpRequest) -> bool:
    secret = expected()
    presented = request.headers.get(HEADER, "")
    return bool(secret) and hmac.compare_digest(presented.encode(), secret.encode())
