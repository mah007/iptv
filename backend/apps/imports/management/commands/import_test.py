"""`manage.py import_test`: the import round trip on the dev stack (DEBUG only; ADR-0025).

`make import-test` starts a throwaway server (rclone's SFTP and HTTPS servers over
synthetic clips) and runs this. It adds a library over `/media/import-test`, an SFTP
source, a folder import and a direct-link import; waits for the importer to copy and
move the files and for the scanner to see and probe them; then removes everything it
made (the files are deleted by the script). The SFTP password comes on stdin.
"""

import sys
import time
from pathlib import Path
from typing import Any

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError, CommandParser

from apps.catalog.models import MediaFile
from apps.core.services import get_setting, set_setting
from apps.imports import services
from apps.imports.models import ImportJob, ImportSource, JobStatus, SourceKind
from apps.library import services as library_services
from apps.library.models import Library

LIBRARY = "Import test"
SOURCE = "Import test SFTP"
FOLDER = "Films/Import Test Clip (2026)"
POLL_S = 0.5


class Command(BaseCommand):
    help = "DEBUG only: import from a test SFTP server and a test HTTPS link, wait for the scan."

    def add_arguments(self, parser: CommandParser) -> None:
        parser.add_argument("--sftp-host", required=True)
        parser.add_argument("--sftp-port", type=int, default=2022)
        parser.add_argument("--sftp-user", required=True)
        parser.add_argument("--link", required=True, help="an https:// link to a test clip")
        parser.add_argument("--timeout", type=float, default=50.0)

    def handle(self, *args: Any, **options: Any) -> None:
        if not settings.DEBUG:
            msg = "import_test runs on the dev stack only (DEBUG)."
            raise CommandError(msg)
        password = sys.stdin.read().strip()
        if not password:
            msg = "Give the test server's password on stdin."
            raise CommandError(msg)
        folder = Path(settings.LIBRARY_ROOT) / "import-test"
        if not folder.is_dir():
            msg = f"{folder} is missing: make import-test creates it."
            raise CommandError(msg)
        if not services.importer_online():
            msg = "The importer isn't running (make up starts it)."
            raise CommandError(msg)
        self._clean()
        reserve = get_setting("library.import_reserve_gb")
        # The dev machine's disk is small; the clips are a few hundred kB.
        set_setting("library.import_reserve_gb", value=0, actor=None)
        started = self.started = time.monotonic()
        try:
            self._round_trip(folder, password, options)
        finally:
            set_setting("library.import_reserve_gb", value=reserve, actor=None)
            self._clean()
        self.stdout.write(f"Import round trip passed in {time.monotonic() - started:.1f} s.")

    def _round_trip(self, folder: Path, password: str, options: dict[str, Any]) -> None:
        library = library_services.create_library(
            {"name": LIBRARY, "kind": "movies", "path": str(folder)}, actor=None, ip=None
        )
        source = services.create_source(
            name=SOURCE,
            kind=SourceKind.SFTP,
            options={
                "host": options["sftp_host"],
                "port": options["sftp_port"],
                "username": options["sftp_user"],
            },
            secrets={"password": password},
            actor=None,
            ip=None,
        )
        request_id = services.queue_request("test", source)
        answer = self._wait(lambda: (services.read_result(request_id) or {}).get("result"), options)
        if not answer or not answer.get("ok"):
            msg = f"The source's Test failed: {answer}"
            raise CommandError(msg)
        self.stdout.write(
            f"  ok    Test: {answer['code']} (host key pinned) at {self._elapsed():.1f} s"
        )
        rights: dict[str, Any] = {
            "library": library,
            "subfolder": "",
            "rights_holder": "Synthetic test media",
            "license_ref": "Generated by make import-test",
            "license_expires_at": None,
            "actor": None,
            "ip": None,
        }
        folder_job = services.create_source_job(
            source=source, items=[{"path": FOLDER, "is_dir": True}], **rights
        )
        link_job = services.create_link_job(
            url=options["link"], file_name="", checksum="", **rights
        )
        for job in (folder_job, link_job):
            finished = self._wait(lambda job=job: self._finished(job), options)
            if finished is None or finished.status != JobStatus.DONE:
                job.refresh_from_db()
                msg = (
                    f"Import {job.origin} did not finish: {job.status} {job.error_code} "
                    f"{job.error}".strip()
                )
                raise CommandError(msg)
            self.stdout.write(
                f"  ok    {job.origin}: {finished.files_done} file(s), "
                f"{finished.bytes_done} bytes, copied and moved into the library "
                f"at {self._elapsed():.1f} s"
            )
        keys = {
            "Import Test Clip (2026)/Import Test Clip (2026).mp4",
            "Import Link Clip (2026).mp4",
        }
        scanned = self._wait(
            lambda: (
                set(
                    MediaFile.objects.filter(
                        library=library, storage_key__in=keys, duration_ms__isnull=False
                    ).values_list("storage_key", flat=True)
                )
                == keys
                or None
            ),
            options,
        )
        if not scanned:
            found = list(
                MediaFile.objects.filter(library=library).values_list("storage_key", "state")
            )
            msg = f"The scanner did not probe both files: {found}"
            raise CommandError(msg)
        self.stdout.write(
            f"  ok    both files scanned and probed by the pipeline at {self._elapsed():.1f} s"
        )
        subtitles = folder / "Import Test Clip (2026)" / "Import Test Clip (2026).en.srt"
        if not subtitles.is_file() or (folder / "Import Test Clip (2026)" / "poster.jpg").exists():
            msg = "The subtitle should be imported and the poster left out."
            raise CommandError(msg)
        self.stdout.write("  ok    the subtitle came along, the poster was left out")

    started = 0.0

    def _elapsed(self) -> float:
        return time.monotonic() - self.started

    @staticmethod
    def _finished(job: ImportJob) -> ImportJob | None:
        job.refresh_from_db()
        return job if job.status not in {JobStatus.QUEUED, JobStatus.RUNNING} else None

    @staticmethod
    def _wait(check: Any, options: dict[str, Any]) -> Any:
        deadline = time.monotonic() + options["timeout"]
        while time.monotonic() < deadline:
            value = check()
            if value:
                return value
            time.sleep(POLL_S)
        return None

    @staticmethod
    def _clean() -> None:
        ImportJob.objects.filter(library__name=LIBRARY).delete()
        ImportJob.objects.filter(source__name=SOURCE).delete()
        ImportSource.objects.filter(name=SOURCE).delete()
        for library in Library.objects.filter(name=LIBRARY):
            library_services.delete_library(library, actor=None, ip=None)
